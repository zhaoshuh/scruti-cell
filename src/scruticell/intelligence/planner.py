"""Processing plan data model for LLM-driven batch-matrix-metadata planning.

Defines the structured output that an LLM should produce when analyzing
a GseReport. This plan drives the execution phase.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from typing import Any


@dataclass
class MatrixMapping:
    """Which file(s) contain the expression matrix and how to read them."""
    file_key: str  # ancestry key from report.file_summaries
    format: str  # canonical: "h5ad", "mtx", "csv", "rds", "loom"
    orientation: str = "auto"  # "cell_x_gene", "gene_x_cell", or "auto"
    transpose: bool = False
    note: str = ""


@dataclass
class BatchMapping:
    """How cells are assigned to batches — with LLM reasoning."""
    gsm_id: str
    file_keys: list[str] = field(default_factory=list)
    cell_count: int = 0
    barcode_prefix: str = ""
    note: str = ""
    # LLM batch reasoning (NEW)
    batch_label: str = ""          # human-readable short name (e.g., "Control_Day0")
    reasoning: str = ""            # WHY this forms a separate batch (biological explanation)
    defining_fields: list[str] = field(default_factory=list)  # which obs columns differ across batches


@dataclass
class FieldMapping:
    """Standardize a raw field name to a canonical name.

    Also supports splitting compound values: when a single GEO field
    contains multiple pieces of information (e.g., "Male_Control_72yr"),
    the value_split instructs how to extract each sub-field.
    """
    raw_field: str
    canonical: str
    source: str = ""
    note: str = ""
    # For compound values: how to split and map sub-parts
    value_split: dict = field(default_factory=dict)


def _resolve_file_keys(batch_dict: dict) -> list[str]:
    """Resolve file_keys from LLM output, handling single-string file_key."""
    fks = batch_dict.get("file_keys")
    if fks and isinstance(fks, list):
        return fks
    fk = batch_dict.get("file_key")
    if isinstance(fk, str) and fk:
        return [fk]
    return []


@dataclass
class ProcessingPlan:
    """Complete batch-matrix-metadata processing plan generated by LLM."""

    gse_id: str

    # Which files are expression matrices
    matrices: list[MatrixMapping] = field(default_factory=list)

    # External metadata files (non-expression, sample/gene annotations)
    metadata_files: list[dict] = field(default_factory=list)

    # How cells map to GSM batches
    batches: list[BatchMapping] = field(default_factory=list)

    # Field name standardization (including compound value splits)
    field_mappings: list[FieldMapping] = field(default_factory=list)

    # Custom processing code (LLM-generated, dataset-specific transformations)
    processing_code: str = ""
    assembly_code: str = ""

    # Injected metadata from multi-step extraction (not LLM-generated)
    _filename_extractions: list = field(default_factory=list)
    _axis_metadata: list = field(default_factory=list)

    # GSM metadata extraction function (Step 2, LLM-generated function)
    extraction_code: str = ""
    # Legacy: per-field extraction expressions (deprecated in favor of extraction_code)
    gsm_meta_extractions: dict = field(default_factory=dict)

    # Consolidated verified mappings (Steps 2+3+4 merged, uncertain items excluded)
    _verified_field_mappings: list = field(default_factory=list)
    _literature_metadata: dict = field(default_factory=dict)

    # Gene handling
    gene_id_system: str = ""  # "symbol" | "ensembl_gene_id" | "entrez_id"
    normalize_genes: bool = True
    drop_duplicate_genes: bool = True

    # Normalization assessment
    normalization: str = ""  # "raw_counts", "log_normalized", "TPM", etc.
    is_raw_counts: bool = False

    # Overall strategy
    strategy_notes: str = ""
    batch_separation_strategy: str = ""  # "per_sample", "per_condition", etc.
    confidence: float = 0.0
    requires_literature_check: bool = False
    literature_check_reason: str = ""

    @classmethod
    def from_llm_response(cls, gse_id: str, json_str: str) -> ProcessingPlan:
        """Parse LLM's JSON response into a ProcessingPlan.

        Filters extra keys from LLM output to match dataclass fields.
        """
        data = json.loads(json_str)

        # Helper: filter dict to only valid dataclass fields
        mapping_fields = {"raw_field", "canonical", "source", "note", "value_split"}

        return cls(
            gse_id=gse_id,
            matrices=[
                MatrixMapping(
                    file_key=m.get("file_key", m.get("filename", m.get("path", ""))),
                    format=m.get("format", "h5"),
                    orientation=m.get("orientation", "auto"),
                    transpose=m.get("transpose", False),
                    note=m.get("note", ""),
                )
                for m in data.get("matrices", [])
            ],
            batches=[
                BatchMapping(
                    gsm_id=b.get("gsm_id", ""),
                    file_keys=_resolve_file_keys(b),
                    cell_count=b.get("cell_count") or 0,
                    barcode_prefix=b.get("barcode_prefix", ""),
                    note=b.get("note", ""),
                    batch_label=b.get("batch_label", ""),
                    reasoning=b.get("reasoning", ""),
                    defining_fields=b.get("defining_fields", []),
                )
                for b in data.get("batches", [])
            ],
            field_mappings=[
                FieldMapping(**{k: v for k, v in f.items() if k in mapping_fields})
                for f in data.get("field_mappings", [])
            ],
            processing_code=data.get("processing_code", ""),
            assembly_code=data.get("assembly_code", ""),
            metadata_files=data.get("metadata_files", []),
            gene_id_system=data.get("gene_id_system", ""),
            normalize_genes=data.get("normalize_genes", True),
            drop_duplicate_genes=data.get("drop_duplicate_genes", True),
            normalization=data.get("normalization", ""),
            is_raw_counts=data.get("is_raw_counts", False),
            strategy_notes=data.get("strategy_notes", ""),
            batch_separation_strategy=data.get("batch_separation_strategy", ""),
            confidence=data.get("confidence", 0.0),
            requires_literature_check=data.get("requires_literature_check", False),
            literature_check_reason=data.get("literature_check_reason", ""),
            gsm_meta_extractions=data.get("gsm_meta_extractions", {}),
            extraction_code=data.get("extraction_code", ""),
            _filename_extractions=data.get("_filename_extractions", []),
            _axis_metadata=data.get("_axis_metadata", []),
            _verified_field_mappings=data.get("_verified_field_mappings", []),
            _literature_metadata=data.get("_literature_metadata", {}),
        )

    def to_dict(self) -> dict[str, Any]:
        """Serialize to dictionary."""
        return {
            "gse_id": self.gse_id,
            "matrices": [m.__dict__ for m in self.matrices],
            "batches": [b.__dict__ for b in self.batches],
            "field_mappings": [f.__dict__ for f in self.field_mappings],
            "processing_code": self.processing_code,
            "assembly_code": self.assembly_code,
            "metadata_files": self.metadata_files,
            "gene_id_system": self.gene_id_system,
            "normalize_genes": self.normalize_genes,
            "drop_duplicate_genes": self.drop_duplicate_genes,
            "normalization": self.normalization,
            "is_raw_counts": self.is_raw_counts,
            "strategy_notes": self.strategy_notes,
            "batch_separation_strategy": self.batch_separation_strategy,
            "confidence": self.confidence,
            "requires_literature_check": self.requires_literature_check,
            "literature_check_reason": self.literature_check_reason,
            "gsm_meta_extractions": self.gsm_meta_extractions,
            "extraction_code": self.extraction_code,
            "_filename_extractions": self._filename_extractions,
            "_axis_metadata": self._axis_metadata,
            "_verified_field_mappings": self._verified_field_mappings,
            "_literature_metadata": self._literature_metadata,
        }

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), indent=indent, ensure_ascii=False)

    def is_valid(self) -> bool:
        """Basic structural validation."""
        if not self.matrices:
            return False
        if not self.batches:
            return False
        for m in self.matrices:
            if not m.file_key or not m.format:
                return False
        for b in self.batches:
            if not b.gsm_id:
                return False
        return True


# LLM prompt template for plan generation
PLAN_GENERATION_SYSTEM_PROMPT = """You are an expert bioinformatician analyzing GEO single-cell RNA-seq datasets. You must systematically extract ALL metadata from ALL available sources before planning the processing.

The input report contains:
- GSE-level metadata: title, summary, overall_design (rich text describing the experiment)
- GSM entries per sample: characteristics dict (pre-parsed key:value pairs), source_name, description
- File summaries per data file: filename, file_type, n_rows, n_cols, columns, preview_rows, barcode_samples, barcode_format, barcode_prefixes
- data_files list: ALL non-soft files (YOU decide which are expression matrices)

=== PHASE 1: SYSTEMATIC METADATA EXTRACTION ===

Before planning, you MUST extract metadata from ALL of these sources:

1.1 **FROM GSE TITLE/SUMMARY/DESIGN (HARD RULE — DO NOT SKIP)**:
   Read the GSE title, summary, and overall_design as free text. These contain the
   experimental description written by the authors. You MUST extract metadata from here.
   
   Example: title="Targeting mitochondrial ROS-CK2-SET-PP2A pathway with ceria nanoparticles..."
   → disease="Alzheimer", drug="Ceria-TPP", target_pathway="ROS-CK2-SET-PP2A"
   
   summary="we used triphenylphosphonium-conjugated ceria nanoparticles (Ceria-TPP) to target
   mitochondrial ROS in APOEe4 human iPSC-derived brain organoid" 
   → organism="Homo sapiens", tissue="brain organoid", cell_source="iPSC-derived",
   treatment="Ceria-TPP", genetic_background="APOE4"
   
   overall_design="We performed single-cell RNA-seq on day 60 human iPSC-derived brain organoids"
   → platform="scRNA-seq", timepoint="day 60", model_system="brain organoid"
   
   Add every discovered piece of metadata as both (a) field_mappings entries with source="gse_text"
   and (b) new columns in processing_code. For global metadata (same for all cells, e.g., disease),
   use: obs['disease'] = 'Alzheimer disease'.
   For per-sample metadata derived from GSE text, add to the appropriate batch.
   If the metadata validates or supplements existing GSM fields, note it.
   If it contradicts GSM fields, flag it in strategy_notes and set requires_literature_check=true.
   
   MINIMUM fields to extract from GSE text: disease/condition, tissue/organ, organism, 
   cell_source, treatment/drug, timepoint, platform, experimental_model.

1.2 **FROM GSM CHARACTERISTICS (HARD RULE)**:
   For each GSM, read ALL characteristic key:value pairs.
   Identify which fields vary across GSMs (these define experimental groups/batches).
   Identify which fields are constants (apply to all samples).
   Flag fields whose values appear to contain multiple pieces of information, and decide how to split each.

1.3 **FROM SOURCE_NAME/DESCRIPTION (HARD RULE)**:
   Read each GSM's source_name and description fields. These often contain
   biological context not captured in characteristics. Extract any additional
   metadata (cell line, tissue origin, treatment details) and add to field_mappings.

1.4 **FROM FILE NAMES (HARD RULE)**:
   Read the filename of each data file. Beyond GSM ID extraction, look for:
   - Sample/group labels (e.g., "Ctrl1", "AML1", "E3_vehicle", "PatientA_Treated")
   - Replicate numbers (e.g., "Rep1", "_R1", "_1")
   - Timepoints (e.g., "Day0", "D7", "Pre", "Post")
   - Treatment conditions (e.g., "vehicle", "treated", "drug", "control")
   Cross-reference these with GSM characteristics for consistency.
   Add any discovered metadata as field_mappings with source="filename".

1.5 **CROSS-GSM COMPARISON (HARD RULE)**:
   Compare characteristics across ALL GSMs to detect:
   - Fields present in some GSMs but missing in others
   - Fields with typos or inconsistent naming
   - Fields whose values differ across GSMs (these are batch-defining)
   - Inconsistencies between file-name-derived metadata and GSM characteristics
   Note discrepancies in strategy_notes.

1.6 **AMBIGUOUS ABBREVIATIONS (HARD RULE)**:
   If you encounter abbreviations you cannot resolve (e.g., "E3" could be genotype or 
   sample ID, "NR" could be "non-responder" or "not reported"), set 
   requires_literature_check=true and note the ambiguity reason.

=== PHASE 2: MATRIX/BATCH PLANNING ===

2.1 **IDENTIFY MATRICES**: From data_files list, decide which are expression matrices by:
   a. Exclude files with "barcode", "feature", "metadata", "annotation", "sample_sheet" in filename
   b. Exclude files with 1-2 columns only
   c. Exclude CSVs where preview_rows contain barcode patterns (14+ ACGT chars)
   d. H5 files with shapes >100x100 ARE matrices
   e. MTX format: if barcode + feature files present, the .mtx.gz file (not .tsv.gz companions) is the matrix

2.2 **MAP TO BATCHES — DISCOVER, DON'T JUST MAP**: GSM_ID does NOT always equal batch.
   Analyze ALL metadata fields across GSMs to determine true batch boundaries.

   Batch discovery signals, in priority order:
   a. **Metadata differences**: Fields whose values differ across GSMs (e.g. treatment,
      timepoint, donor_id) may define batches. If 3 GSMs share donor_id=P01 but differ
      in timepoint, consider timepoint-based batching. If 2 GSMs have the same condition
      and tissue, consider merging them into one batch.
   b. **File patterns**: If gsm_file_map maps each GSM to its own file, that's a STARTING
      POINT but you may GROUP or SPLIT based on metadata.
   c. **Barcode prefixes**: Multiple barcode prefixes in one matrix file → separate sample
      sources (cellranger aggr merge). Split into different batches.
   d. **Field combinations**: Sometimes no single field defines batches, but a COMBINATION
      does. Example: donor_id + timepoint together define batches.

   For EACH batch, you MUST also provide:
   - "batch_label": human-readable short name (e.g. "P01_Day0", "Control_Lung")
   - "reasoning": WHY this is a separate batch, referencing specific metadata fields.
     Example: "Different treatment: DMSO vs Drug X; all other metadata identical"
     Example: "Independent patient P03; different donor, same tissue and protocol"
   - "defining_fields": which GSM fields DIFFER across batches (e.g. ["treatment", "timepoint"])

   Also output "batch_separation_strategy" at top level:
   "per_sample" / "per_condition" / "per_timepoint" / "per_patient" /
   "per_treatment" / "by_gsm_file_map" / "by_barcode_prefix" /
   "field_combination" / "single_batch"

2.3 **FIELD STANDARDIZATION**: Add field_mappings for raw GEO field name → canonical name.
   Canonical names: tissue, cell_type, treatment, genotype, disease, sex, age, timepoint, 
   patient_id, sample_id, batch, organism, platform, normalization.

2.4 **GENE/NORM ASSESSMENT**: Detect gene_id_system. Use ONLY: "symbol" | "ensembl_gene_id" | "entrez_id".

2.5 **BARCODE PREFIXES**: If barcode_prefixes exist, extract embedded metadata
   (e.g., "Patient1_Treated_Day7" → patient/treatment/timepoint).

=== PHASE 3: PROCESSING CODE ===

Generate a "processing_code" field with Python function `def process(obs, var, adata)`.
The code must:
- Include ALL field_mappings as obs.rename() calls
- Include ALL compound value splits as str.split()/str.extract() calls
- Add ALL discovered metadata columns FROM ALL SOURCES (gse_text, filename, descriptions)
  For global metadata (same value for all cells): obs['column'] = 'value'
  For per-batch metadata: use obs['batch'].map() or conditional assignment
- Handle missing values, edge cases, and strip whitespace from all string columns
- Use only: pd (pandas), np (numpy), re (no file I/O, network, os, subprocess)
- End with "return obs, var, adata"

Return ONLY the JSON object with: matrices, batches, field_mappings, gene_id_system,
normalize_genes, drop_duplicate_genes, normalization, is_raw_counts, processing_code,
strategy_notes, batch_separation_strategy, confidence, requires_literature_check,
literature_check_reason. Within each batch object, include: gsm_id, file_keys,
cell_count, barcode_prefix, note, batch_label, reasoning, defining_fields.
No other text."""


def build_plan_prompt(report_json: str) -> str:
    """Build the user prompt for plan generation from a GseReport JSON."""
    return f"""Analyze this GEO dataset inspection report and produce a processing plan.

REPORT:
{report_json}

Generate a JSON processing plan following the rules above."""


def build_validation_prompt(plan_json: str, report_json: str, issues: str) -> str:
    """Build a prompt for the LLM to fix plan validation issues."""
    return f"""The processing plan below has validation issues. Fix them.

PLAN:
{plan_json}

ISSUES FOUND:
{issues}

ORIGINAL REPORT (for reference):
{report_json}

Return the CORRECTED JSON plan. Only fix the issues; keep valid parts unchanged."""
